/**
 * PostgreSQL catalog queries used by PostgresAdapter.
 * Every parameter uses a $n placeholder (no string concatenation of user input).
 * Uses pg_catalog (not information_schema) so materialized views are visible too.
 */

/** Relation kinds shown: table, partitioned table, view, materialized view, foreign table. */
const RELKINDS = "('r', 'p', 'v', 'm', 'f')";
const USER_SCHEMAS =
  "n.nspname NOT IN ('pg_catalog', 'information_schema') AND n.nspname NOT LIKE 'pg\\_%'";

/**
 * $1 schema (text|null), $2 schema whitelist (text[]|null), $3 search word (text|null), $4 limit.
 * Child partitions are hidden so the list is not flooded; their parent table is still shown.
 */
export const LIST_TABLES_SQL = `
SELECT n.nspname AS schema_name,
       c.relname AS table_name,
       CASE WHEN c.relkind IN ('v', 'm') THEN 'view' ELSE 'table' END AS table_type
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ${RELKINDS}
  AND NOT c.relispartition
  AND ${USER_SCHEMAS}
  AND has_schema_privilege(n.oid, 'USAGE')
  AND ($1::text IS NULL OR n.nspname = $1::text)
  AND ($2::text[] IS NULL OR n.nspname = ANY ($2::text[]))
  AND ($3::text IS NULL OR c.relname ILIKE '%' || $3::text || '%')
ORDER BY n.nspname, c.relname
LIMIT $4::int`;

/**
 * Find relations by name. An exact name is preferred, then a case-insensitive match.
 * $1 table name, $2 schema (text|null), $3 schema whitelist (text[]|null).
 */
export const FIND_TABLE_SQL = `
SELECT c.oid::int8::text AS oid,
       n.nspname AS schema_name,
       c.relname AS table_name,
       CASE WHEN c.relkind IN ('v', 'm') THEN 'view' ELSE 'table' END AS table_type,
       (c.relname = $1::text) AS exact
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ${RELKINDS}
  AND ${USER_SCHEMAS}
  AND (c.relname = $1::text OR lower(c.relname) = lower($1::text))
  AND ($2::text IS NULL OR n.nspname = $2::text OR lower(n.nspname) = lower($2::text))
  AND ($3::text[] IS NULL OR n.nspname = ANY ($3::text[]))
ORDER BY (c.relname = $1::text) DESC,
         (n.nspname = ANY (current_schemas(false))) DESC,
         n.nspname
LIMIT 20`;

/** $1 relation oid (text). */
export const COLUMNS_SQL = `
SELECT a.attname AS column_name,
       format_type(a.atttypid, a.atttypmod) AS data_type,
       NOT a.attnotnull AS nullable,
       COALESCE(
         pg_get_expr(d.adbin, d.adrelid),
         CASE a.attidentity
           WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
           WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
         END
       ) AS default_value
FROM pg_catalog.pg_attribute a
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = $1::text::oid
  AND a.attnum > 0
  AND NOT a.attisdropped
ORDER BY a.attnum`;

/** $1 relation oid (text). */
export const PRIMARY_KEY_SQL = `
SELECT a.attname AS column_name
FROM pg_catalog.pg_constraint con
CROSS JOIN LATERAL unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord)
JOIN pg_catalog.pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
WHERE con.conrelid = $1::text::oid
  AND con.contype = 'p'
ORDER BY k.ord`;

/** $1 relation oid (text). */
export const FOREIGN_KEYS_SQL = `
SELECT con.conname AS constraint_name,
       ARRAY(
         SELECT a.attname
         FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord)
         JOIN pg_catalog.pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
         ORDER BY k.ord
       )::text[] AS columns,
       rn.nspname AS ref_schema,
       rc.relname AS ref_table,
       ARRAY(
         SELECT a.attname
         FROM unnest(con.confkey) WITH ORDINALITY AS k(attnum, ord)
         JOIN pg_catalog.pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum
         ORDER BY k.ord
       )::text[] AS ref_columns
FROM pg_catalog.pg_constraint con
JOIN pg_catalog.pg_class rc ON rc.oid = con.confrelid
JOIN pg_catalog.pg_namespace rn ON rn.oid = rc.relnamespace
WHERE con.conrelid = $1::text::oid
  AND con.contype = 'f'
ORDER BY con.conname`;

/** $1 relation oid (text). Expression index columns are shown as their expression. */
export const INDEXES_SQL = `
SELECT i.relname AS index_name,
       ix.indisunique AS is_unique,
       ARRAY(
         SELECT pg_get_indexdef(ix.indexrelid, g.n, true)
         FROM generate_series(1, ix.indnkeyatts) AS g(n)
       )::text[] AS columns
FROM pg_catalog.pg_index ix
JOIN pg_catalog.pg_class i ON i.oid = ix.indexrelid
WHERE ix.indrelid = $1::text::oid
ORDER BY ix.indisprimary DESC, i.relname`;
